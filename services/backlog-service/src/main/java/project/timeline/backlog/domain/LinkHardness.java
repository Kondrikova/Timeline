package project.timeline.backlog.domain;

/**
 * Отделяет логическую необходимость от предпочтения планировщика. Это разница
 * между «делать после» и «ставим после», и она не структурная, поэтому выражена
 * атрибутом, а не удвоением числа типов.
 */
public enum LinkHardness {

	/** Нарушение невозможно физически: участвует в каскаде, даёт ERROR. */
	HARD,

	/** Пожелание порядка: план не двигает, даёт WARNING. */
	SOFT
}
